-- A dev database as Hibernate's ddl-auto=update left it before Flyway: no flyway_schema_history, the
-- RezLive-era column names, and some rows. The DDL is pg_dump --schema-only of a database that
-- develop 3e1acdd built (schema qualifiers removed). Used by SchemaMigrationTest; run with
-- search_path set to a scratch schema. Frozen: do not update it when the schema changes.

CREATE TABLE city (
    city_code character varying(255) NOT NULL,
    country_code character varying(2),
    name character varying(255) NOT NULL
);
CREATE TABLE country (
    country_code character varying(2) NOT NULL,
    name character varying(255) NOT NULL
);
CREATE TABLE hotel (
    hotel_code bigint NOT NULL,
    city_code character varying(255),
    country_code character varying(2),
    description oid,
    hotel_address character varying(1024),
    hotel_postal_code character varying(255),
    latitude double precision,
    longitude double precision,
    name character varying(255),
    rating integer
);
CREATE TABLE hotel_booking (
    id bigint NOT NULL,
    agent_ref_no character varying(255),
    arrival_date date,
    rez_booking_code character varying(255),
    rez_booking_id character varying(255) NOT NULL,
    cancellation_charges character varying(255),
    cancelled_at timestamp(6) with time zone,
    city character varying(255),
    country_code character varying(255),
    created_at timestamp(6) with time zone,
    currency character varying(255),
    departure_date date,
    hotel_id character varying(255),
    hotel_name character varying(255),
    price character varying(255),
    provider character varying(255),
    search_session_id character varying(1024),
    status character varying(255)
);
ALTER TABLE hotel_booking ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME hotel_booking_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
CREATE TABLE hotel_image (
    id bigint NOT NULL,
    hotel_code bigint NOT NULL,
    image character varying(2048)
);
ALTER TABLE hotel_image ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME hotel_image_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
CREATE TABLE property_amenity (
    hotel_code bigint NOT NULL,
    hotel_amenities oid
);
CREATE TABLE room_amenity (
    hotel_code bigint NOT NULL,
    room_amenities oid
);
ALTER TABLE ONLY city
    ADD CONSTRAINT city_pkey PRIMARY KEY (city_code);
ALTER TABLE ONLY country
    ADD CONSTRAINT country_pkey PRIMARY KEY (country_code);
ALTER TABLE ONLY hotel_booking
    ADD CONSTRAINT hotel_booking_pkey PRIMARY KEY (id);
ALTER TABLE ONLY hotel_image
    ADD CONSTRAINT hotel_image_pkey PRIMARY KEY (id);
ALTER TABLE ONLY hotel
    ADD CONSTRAINT hotel_pkey PRIMARY KEY (hotel_code);
ALTER TABLE ONLY hotel_booking
    ADD CONSTRAINT idx_booking_agent_ref UNIQUE (agent_ref_no);
ALTER TABLE ONLY hotel_booking
    ADD CONSTRAINT idx_booking_rez_id UNIQUE (rez_booking_id);
ALTER TABLE ONLY property_amenity
    ADD CONSTRAINT property_amenity_pkey PRIMARY KEY (hotel_code);
ALTER TABLE ONLY room_amenity
    ADD CONSTRAINT room_amenity_pkey PRIMARY KEY (hotel_code);
CREATE INDEX idx_city_country ON city USING btree (country_code);
CREATE INDEX idx_hotel_city ON hotel USING btree (city_code);
CREATE INDEX idx_hotel_country ON hotel USING btree (country_code);
CREATE INDEX idx_hotel_image_hotel ON hotel_image USING btree (hotel_code);

