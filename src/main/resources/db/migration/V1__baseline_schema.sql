-- Baseline: the schema exactly as Hibernate's ddl-auto=update created it before Flyway was adopted
-- (OPS-1 / KAN-84; captured from develop 3e1acdd with pg_dump --schema-only).
--
-- A clean database runs this script. A database that ddl-auto=update already built has these tables
-- but no flyway_schema_history; spring.flyway.baseline-on-migrate marks it as version 1 and skips
-- this script, so its data is never touched. Later migrations then run on both kinds alike.
--
-- Never edit this file. Change the schema with a new, timestamp-versioned migration (AGENTS.md §5).
--
-- Note: the three @Lob String columns are Postgres large-object references (oid), because that is
-- how Hibernate maps @Lob String on PostgreSQL. Kept as-is here so existing data stays readable.

CREATE TABLE country (
    country_code varchar(2)   NOT NULL,
    name         varchar(255) NOT NULL,
    CONSTRAINT country_pkey PRIMARY KEY (country_code)
);

CREATE TABLE city (
    city_code    varchar(255) NOT NULL,
    country_code varchar(2),
    name         varchar(255) NOT NULL,
    CONSTRAINT city_pkey PRIMARY KEY (city_code)
);
CREATE INDEX idx_city_country ON city (country_code);

CREATE TABLE hotel (
    hotel_code        bigint NOT NULL,
    city_code         varchar(255),
    country_code      varchar(2),
    description       oid,
    hotel_address     varchar(1024),
    hotel_postal_code varchar(255),
    latitude          double precision,
    longitude         double precision,
    name              varchar(255),
    rating            integer,
    CONSTRAINT hotel_pkey PRIMARY KEY (hotel_code)
);
CREATE INDEX idx_hotel_city ON hotel (city_code);
CREATE INDEX idx_hotel_country ON hotel (country_code);

CREATE TABLE hotel_image (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    hotel_code bigint NOT NULL,
    image      varchar(2048),
    CONSTRAINT hotel_image_pkey PRIMARY KEY (id)
);
CREATE INDEX idx_hotel_image_hotel ON hotel_image (hotel_code);

CREATE TABLE property_amenity (
    hotel_code      bigint NOT NULL,
    hotel_amenities oid,
    CONSTRAINT property_amenity_pkey PRIMARY KEY (hotel_code)
);

CREATE TABLE room_amenity (
    hotel_code     bigint NOT NULL,
    room_amenities oid,
    CONSTRAINT room_amenity_pkey PRIMARY KEY (hotel_code)
);

CREATE TABLE hotel_booking (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY,
    agent_ref_no         varchar(255),
    arrival_date         date,
    rez_booking_code     varchar(255),
    rez_booking_id       varchar(255) NOT NULL,
    cancellation_charges varchar(255),
    cancelled_at         timestamp(6) with time zone,
    city                 varchar(255),
    country_code         varchar(255),
    created_at           timestamp(6) with time zone,
    currency             varchar(255),
    departure_date       date,
    hotel_id             varchar(255),
    hotel_name           varchar(255),
    price                varchar(255),
    provider             varchar(255),
    search_session_id    varchar(1024),
    status               varchar(255),
    CONSTRAINT hotel_booking_pkey PRIMARY KEY (id),
    CONSTRAINT idx_booking_agent_ref UNIQUE (agent_ref_no),
    CONSTRAINT idx_booking_rez_id UNIQUE (rez_booking_id)
);
